// 回合結束守門（2026-10-28 使用者要求，盤點「需要介入過多」後做的）：
// A. 被背景通知喚醒後只回 "No response requested." 就停 → 擋下，要它接著做或交代一行狀態。
// B. 結尾在問使用者要不要做（選單、問句）→ 擋一次，提醒可回退又在範圍內的事直接做；真該問就直接結束。
// 重來那次（stop_hook_active）一律放行，不會無限迴圈。程式碼區塊不算結尾文字。
const EMPTY = /^No response requested\.?$/i;
const config = require('./das-config.js');

// 結尾問使用者的樣子
const ASK = /(要不要|要我|需要我|是否要|是否需要|回覆?[「『][^」』\n]{1,12}[」』][^。\n]{0,6}[我就]|請選|可以嗎|好嗎|行嗎|OK 嗎|嗎[？?]|[？?]\s*$)/;
// 碰到紅線的問題本來就該問，不擋
const RED = /(確認執行|刪除|刪掉|清掉|清空|封存|移除|DROP|TRUNCATE|對外|寄出|寄給|發送|發給|送出|\bpush\b|\bPR\b|帳密|密碼|權限|付費|花錢|費用|算錢|金額|損益|部位|下單|正式|htdocs|取代|覆蓋|上架|排程|上線|部署|核准單)/i;

// C（2026-11-03）：把能自己做的手動步驟丟給使用者（雙擊 .cmd、拿分享連結、去設定頁、貼連結、叫他登入）。
// 當晚依序叫使用者跑 .cmd、要分享連結、找設定頁，被罵「很不體諒使用者」；其實 nblm Edge 已有 Google 登入，自己走得通。
// 只用在 das-hooks.json 明確設定的工作區；其他工作區可能有必須由本人完成的現場操作，預設不擋。
// 「雙擊」單獨常是介面說明（雙擊改名），只抓雙擊檔案；「截圖給我」在重現不了的畫面問題是正當的，不抓。
// 11-03 Astra 對抗：整則比對會漏「請在 Edge 登入」、誤擋「我已取得分享連結」，而且別處出現一個豁免字就整則放行。改成逐句：
// 雙擊檔案本身就是叫人動手；分享連結、登入要同一句裡有請你做的字眼。豁免字和否定也只看同一句。
// 11-03 DEMO 影片那段：「請把下面這段貼到它的對話框」「請您處理：打開 <網址> 按停止」「用您那邊做兩步」連四次漏擋。
const DBLCLICK = /(雙擊|點兩下)[^。\n]{0,60}(\.cmd|\.bat|這個檔|檔案)|(網址|連結)貼(給我|回)|按[「『]?(分享|複製連結)|貼(到|進|在|上)[^。\n]{0,20}(對話框|輸入框|session|視窗|分頁)|請(您|你)處理|用(您|你)?(那邊|手機|自己的瀏覽器)[^。\n]{0,6}(做|按|打開|貼)|打開\s*https?:\/\/\S+[^。\n]{0,20}按/i;
const ASK_YOU = /(請(?!求)|麻煩|幫我|(你|您)(先|去|到|自己|可以|再|幫))/;
const ACT = /(分享(連結|網址)|複製連結|取得(網址|連結)|(網址|連結)貼(給我|上來|過來)|登入(?!的|成功|過|了|失效|狀態|資料))/;
// 否定、或在轉述以前叫過他做（「叫你雙擊檔案」）
const NOT_YOU = /(不用|不需要|不必|無需|免)(你|您)?[^，,。\n]{0,6}(雙擊|點兩下|複製|取得|貼|登入|執行|開)|(叫|要|讓)(你|您)[^，,。\n]{0,6}(雙擊|點兩下|複製|取得|貼|登入|執行|開)/;
// 真的只有本人能做、本來就該交出去的（別人的電腦、網頁 OAuth 授權），前面不能是「不需要」
// 11-03 回放 14 天 18 則命中人工判：12 則誤擋多是同事／srv-old 登入、GitHub／Google 授權網址、引述
const HANDOFF_OK = /(會話清單|logged-in-sessions|推播|通行金鑰|密碼金鑰|驗證碼|核准單|安全輸入|UAC|系統管理員|現場|內網|公司機|公司電腦|同事|本人|請人|她|他(?!們)|管理者|GitHub|OAuth|wrangler|授權網址|輸入[^。\n]{0,4}密碼|（等你回覆）)/gi;
function handoff(prose) {
  // 引號裡和 > 引用行是在轉述，不算要求
  prose = prose.replace(/[「『][^」』\n]*[」』]/g, ' ').replace(/^\s*>.*$/gm, ' ');
  return prose.split(/[。！？!?\n]/).some((s) => {
    if (!(DBLCLICK.test(s) || (ASK_YOU.test(s) && ACT.test(s))) || NOT_YOU.test(s)) return false;
    return ![...s.matchAll(HANDOFF_OK)].some((m) => !/(不用|不需要|不必|無需|免)$/.test(s.slice(Math.max(0, m.index - 4), m.index)));
  });
}

// D（2026-11-03 傍晚）：試一兩條路就宣告「做不到」。DEMO 影片那段 CDP 瀏覽器被 claude.ai 擋下後，連三則說「接不上／停不了／做不到」，
// 還先花掉使用者一組驗證碼；桌面上已登入的 Chrome＋真實滑鼠一直都在，使用者推三次才去試，試了就通。只擋一次，重答時放行。
const GIVEUP = /((我|這邊|這台|本機|目前|現在)[^。\n，,]{0,10}(做不到|辦不到|停不了|接不上|拿不到|連不上|沒辦法)|這條路走不通)/;
function giveup(prose) {
  prose = prose.replace(/[「『][^」』\n]*[」』]/g, ' ').replace(/^\s*>.*$/gm, ' ');
  // 14 天回放的誤擋：別人自己的瀏覽器、「沒辦法確定」、條件句、功能還沒做、紅線（轉帳）
  return prose.split(/[。！？!?\n]/).some((s) => GIVEUP.test(s) &&
    !/(不是|並非)[^。\n]{0,4}(做不到|辦不到|沒辦法)|(宣告|說|說成|回報)[^。\n]{0,2}(做不到|辦不到|停不了|接不上|拿不到|沒辦法)|(你|您)自己的|確定|[時後][，,]|的話|還沒做|只有規格|轉帳|付款|匯款|銀行/.test(s));
}

function tail(text) {
  const prose = text.replace(/```[\s\S]*?```/g, ' ');
  const lines = prose.split('\n').map((l) => l.trim()).filter(Boolean);
  return lines.slice(-2).join('\n');
}

function verdict(e) {
  if (e.stop_hook_active) return null;
  const text = typeof e.last_assistant_message === 'string' ? e.last_assistant_message.trim() : '';
  // 2026-10-29：只吐一個看不見的組合字元（U+0338）就結束，舊版當成有回覆放行。沒有任何字母、數字、中文就算空回合。
  if (!/[\p{L}\p{N}]/u.test(text)) {
    return '這回合沒有任何實際內容就結束了（空白或只有看不見的字元）。回到使用者這回合的要求接著做；' +
      '做不下去就用繁體中文說明卡在哪裡、下一步是什麼。';
  }
  if (EMPTY.test(text)) {
    return '這回合是被背景通知或系統訊息喚醒的，不要只回空話就停。先讀通知內容：原本的工作還沒完成就接著做；' +
      '真的沒事可做，就用一行繁體中文交代狀態（什麼還在跑、大約何時好、下一步是什麼）。';
  }
  const prose = text.replace(/```[\s\S]*?```/g, ' ');
  if (config.applies(e.cwd) && handoff(prose)) {
    return '這則回覆要使用者自己動手（雙擊、拿連結、去設定頁、登入之類）。使用者規則：能自己做的不要丟給他。' +
      '先查本機會話清單與任務範圍內可用工具，在既有授權內操作；只有本人驗證（推播、通行金鑰、驗證碼）、紅線或核准單才交給他，' +
      '交接時講清楚他做完你接著做什麼。確實只能請他做，就在回覆裡寫明已查過會話清單、為什麼不行。';
  }
  if (config.applies(e.cwd) && giveup(prose)) {
    return '宣告做不到前，先盤點任務範圍內的備忘、已登入會話、本機工具與 API。' +
      '只在授權明確、不違反明示限制且維持原驗收條件時採用等效唯讀方法；使用者要求失敗即停或限定工具時照做。' +
      '仍有阻塞就如實交代已查過什麼、缺什麼，不接管或結束非本次啟動的共用程序。';
  }
  const t = tail(text);
  // 2026-11-01：蒸餾模式（燒杯）每回合正事做完後附一題「🧪 蒸餾提問」，是使用者要的，不擋。
  if (/🧪 ?蒸餾提問/.test(t)) return null;
  if (!ASK.test(t) || RED.test(t)) return null;
  return '這則回覆的結尾在問使用者。使用者規則：可回退、又在這回合要求範圍內的事，直接照你建議的預設做完再回報，並列出做了哪些假設。' +
    '只有紅線（算錢／資料邏輯、刪資料、對外送出、帳密權限、花錢）、超出使用者這回合要的範圍，或缺了只有使用者知道的資訊時才問。' +
    '如果確實該問（或使用者這回合本來就要你問），只輸出「（等你回覆）」這五個字就結束，前面的內容使用者已經看到了，不要重寫或重複。';
}

if (require.main === module) {
  let input = '';
  process.stdin.on('data', (c) => (input += c)).on('end', () => {
    try {
      const reason = verdict(JSON.parse(input));
      if (reason) process.stdout.write(JSON.stringify({ decision: 'block', reason }));
    } catch {}
  });
}

module.exports = { verdict };
