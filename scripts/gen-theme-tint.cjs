// gen-theme-tint.cjs — 色澤微調 (2026-10-31): the Tailwind palettes that do not follow the theme (red, green, amber…)
// get a light colour filter per theme. Each shade keeps its own lightness (OKLab L, within 0.02 where the result leaves sRGB) and moves its hue/chroma (a, b)
// a few percent toward the theme's primary — what a 10–20 % "color" blend layer would do — so contrast stays put.
// Writes the block between the markers in src/index.css; tailwind.config.js reads the same variables with the
// Tailwind value as fallback, so themes without a block (PRESENTER) look exactly as before.
// usage: node scripts/gen-theme-tint.cjs
'use strict';
const fs = require('fs'), path = require('path');
const colors = require('tailwindcss/colors');

const PALETTES = ['red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'indigo',
  'violet', 'purple', 'fuchsia', 'pink', 'rose', 'slate', 'zinc', 'neutral', 'stone'];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
// theme → [primary as in index.css (h s% l%), strength]
const THEMES = {
  light: ['245 58% 57%', 0.10],
  dark: ['243 88% 75%', 0.12],
  synthwave: ['322 100% 67%', 0.18],
  aurora: ['160 70% 50%', 0.15],
  washi: ['88 34% 33%', 0.15],
};

const hex2rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
function hsl2rgb(str) {
  const [h, s, l] = str.split(/\s+/).map(parseFloat);
  const S = s / 100, L = l / 100, a = S * Math.min(L, 1 - L);
  const f = (n) => { const k = (n + h / 30) % 12; return L - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)); };
  return [f(0), f(8), f(4)];
}
const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const gam = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
function toOklab([r, g, b]) {
  [r, g, b] = [r, g, b].map(lin);
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s];
}
function fromOklab([L, A, B]) {
  const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
  const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
  const s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
  const rgb = [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s];
  return rgb.map((c) => Math.round(Math.max(0, Math.min(1, gam(c))) * 255));
}
function tint(hex, primary, t) {
  const [L, a, b] = toOklab(hex2rgb(hex)), [, ta, tb] = toOklab(primary);
  return fromOklab([L, a + (ta - a) * t, b + (tb - b) * t]).join(' ');
}

const blocks = Object.entries(THEMES).map(([name, [p, t]]) => {
  const primary = hsl2rgb(p);
  const vars = PALETTES.flatMap((pal) => SHADES.filter((s) => colors[pal][s]).map((s) => `    --c-${pal}-${s}: ${tint(colors[pal][s], primary, t)};`));
  return `  html.theme-${name} {\n${vars.join('\n')}\n  }`;
});

const BEGIN = '/* 色澤微調 BEGIN (generated by scripts/gen-theme-tint.cjs, do not edit by hand) */';
const END = '/* 色澤微調 END */';
const file = path.join(__dirname, '..', 'src', 'index.css');
let css = fs.readFileSync(file, 'utf8');
const block = `${BEGIN}\n${blocks.join('\n')}\n${END}`;
const i = css.indexOf(BEGIN), j = css.indexOf(END);
css = i >= 0 && j > i ? css.slice(0, i) + block + css.slice(j + END.length) : css.trimEnd() + '\n\n' + block + '\n';
fs.writeFileSync(file, css);
console.log(`gen-theme-tint: ${Object.keys(THEMES).length} themes × ${PALETTES.length} palettes`);
if (process.argv.includes('--check')) {
  for (const [name, [p, t]] of Object.entries(THEMES)) console.log(name, 'red-600', colors.red[600], '→', tint(colors.red[600], hsl2rgb(p), t), '| green-500', colors.green[500], '→', tint(colors.green[500], hsl2rgb(p), t));
}
module.exports = { PALETTES };
